// variants helper: base sku prefix + array of [color, material, priceDelta, stock]
function variants(prefix, rows) {
  return rows.map(([color, material, priceDelta, stock], i) => ({
    sku: `${prefix}-${String(i + 1).padStart(2, '0')}`,
    color,
    material,
    priceDelta,
    stock,
  }));
}

